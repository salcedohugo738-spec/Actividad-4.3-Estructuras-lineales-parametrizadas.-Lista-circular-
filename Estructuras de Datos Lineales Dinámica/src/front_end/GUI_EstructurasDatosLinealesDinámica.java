    private void btn_VaciarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_VaciarActionPerformed
        if (lista.isEmpty()) {
            mostrarInfo("La lista circular ya está vacía.");
            return;
        }
        int cantidad = lista.getTamanio();
        lista.vaciarLista();
        actualizarVista();
        mostrarInfo("Se vació la lista circular. Nodos eliminados: " + cantidad + "\nisEmpty() = " + lista.isEmpty());
    }//GEN-LAST:event_btn_VaciarActionPerformed

