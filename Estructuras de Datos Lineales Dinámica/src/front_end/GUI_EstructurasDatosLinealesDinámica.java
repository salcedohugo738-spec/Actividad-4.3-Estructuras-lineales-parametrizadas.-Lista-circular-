    /** Inserta un trabajo al inicio, al final o en la posición indicada. */
    private void insertar(int modo) {
        try {
            Trabajo trabajo = crearTrabajoDesdeFormulario();
            switch (modo) {
                case INICIO -> lista.insertarInicio(trabajo);
                case FINAL -> lista.insertarFinal(trabajo);
                default -> {
                    int posicion = parsearEntero(txt_Posicion.getText(), "Posición", 0);
                    lista.insertarPosicion(trabajo, posicion);
                }
            }
            limpiarFormulario();
            actualizarVista();
        } catch (IllegalArgumentException | IllegalStateException ex) {
            mostrarError(ex.getMessage());
        }
    }

    /** Valida los campos y crea la subclase de Trabajo según el tipo elegido. */
    private Trabajo crearTrabajoDesdeFormulario() {
        String titulo = textoObligatorio(txt_Titulo.getText(), "Título");
        String autor = textoObligatorio(txt_autor.getText(), "Autor");
        int anio = parsearEntero(txt_AñoPublicacion.getText(), "Año de publicación", 1);
        String tipo = (String) cBox_TipoPublicacion.getSelectedItem();
        if ("Libro".equals(tipo)) {
            int paginas = parsearEntero(txtNumPaginas.getText(), "Nº de Páginas", 1);
            return new Libro(titulo, autor, anio, paginas);
        } else if ("Revista".equals(tipo)) {
            int edicion = parsearEntero(txtNumEdicion.getText(), "Nº de Edición", 1);
            return new Revista(titulo, autor, anio, edicion);
        } else {
            String conferencia = textoObligatorio(txtConferencia.getText(), "Nombre de Conferencia");
            return new Articulo(titulo, autor, anio, conferencia);
        }
    }

    private String textoObligatorio(String texto, String campo) {
        if (texto == null || texto.trim().isEmpty()) {
            throw new IllegalArgumentException("El campo '" + campo + "' no puede estar vacío.");
        }
        return texto.trim();
    }

    /** Convierte a entero validando que sea un número y que sea >= minimo. */
    private int parsearEntero(String texto, String campo, int minimo) {
        String t = textoObligatorio(texto, campo);
        int valor;
        try {
            valor = Integer.parseInt(t);
        } catch (NumberFormatException ex) {
            throw new IllegalArgumentException("El campo '" + campo + "' debe ser un número entero válido.");
        }
        if (valor < minimo) {
            throw new IllegalArgumentException("El campo '" + campo + "' debe ser "
                    + (minimo > 0 ? "mayor a cero." : "mayor o igual a cero."));
        }
        return valor;
    }

    /** Habilita solo el campo propio del tipo elegido y deshabilita (y limpia) los demás. */
    private void actualizarCamposPorTipo() {
        String tipo = (String) cBox_TipoPublicacion.getSelectedItem();
        boolean libro = "Libro".equals(tipo);
        boolean revista = "Revista".equals(tipo);
        boolean articulo = "Articulo".equals(tipo);
        txtNumPaginas.setEnabled(libro);
        jLabel2.setEnabled(libro);
        txtNumEdicion.setEnabled(revista);
        jLabel3.setEnabled(revista);
        txtConferencia.setEnabled(articulo);
        jLabel4.setEnabled(articulo);
        if (!libro) {
            txtNumPaginas.setText("");
        }
        if (!revista) {
            txtNumEdicion.setText("");
        }
        if (!articulo) {
            txtConferencia.setText("");
        }
    }

    /** Refresca la secuencia circular y el elemento actual. */
    private void actualizarVista() {
        txtVisualizacion.setText(lista.mostrarTodos());
        txtVisualizacion.setCaretPosition(0);
        if (lista.isEmpty()) {
            txtActual.setText("No hay elemento actual: la lista está vacía.");
        } else {
            txtActual.setText("Elemento actual (posición " + lista.getPosicionActual()
                    + " de 0 a " + (lista.getTamanio() - 1) + "):\n\n" + lista.consultarActual());
        }
        txtActual.setCaretPosition(0);
    }

    private void limpiarFormulario() {
        txt_Titulo.setText("");
        txt_autor.setText("");
        txt_AñoPublicacion.setText("");
        txt_Posicion.setText("");
        txtNumPaginas.setText("");
        txtNumEdicion.setText("");
        txtConferencia.setText("");
        txt_Titulo.requestFocusInWindow();
    }

    private void mostrarError(String mensaje) {
        JOptionPane.showMessageDialog(this, mensaje, "Validación", JOptionPane.WARNING_MESSAGE);
    }

    private void mostrarInfo(String mensaje) {
        JOptionPane.showMessageDialog(this, mensaje, "Lista circular", JOptionPane.INFORMATION_MESSAGE);
    }

